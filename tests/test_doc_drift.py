def _assert_clean(problems: list[str]) -> None:
    assert not problems, "\n" + "\n".join(problems)


def _architecture_text() -> str:
    return (ROOT / ".claude" / "architecture.md").read_text()


def _doc_id(path: Path) -> str:
    return str(path.relative_to(ROOT))


def test_doc_paths_include_core_docs():
    ids = {_doc_id(p) for p in DOC_PATHS}
    assert {"README.md", ".claude/architecture.md", ".claude/design.md"} <= ids


@pytest.mark.parametrize("doc", DOC_PATHS, ids=_doc_id)
def test_docs_path_references_exist(doc):
    _assert_clean(check_path_references(doc, doc.read_text()))


def test_docs_cover_every_src_module():
    text = "\n".join((ROOT / ".claude" / name).read_text() for name in ("design.md", "architecture.md"))
    _assert_clean(check_modules_documented(ROOT / ".claude" / "design.md", text))


def test_docs_invariant_tests_exist():
    path = ROOT / ".claude" / "architecture.md"
    _assert_clean(check_invariant_tests(path, path.read_text()))


@pytest.mark.parametrize("doc", DOC_PATHS, ids=_doc_id)
def test_docs_adr_references_exist(doc):
    known = set(ADR_HEADING_RE.findall(_architecture_text()))
    _assert_clean(check_adr_references(doc, doc.read_text(), known))


@pytest.mark.parametrize("doc", DOC_PATHS, ids=_doc_id)
def test_docs_release_stages_are_handled(doc):
    stages = release_stages((ROOT / "release.sh").read_text())
    assert stages, "could not parse the case statement in release.sh"
    _assert_clean(check_release_stages(doc, doc.read_text(), stages))


@pytest.mark.parametrize("doc", DOC_PATHS, ids=_doc_id)
def test_docs_have_no_hardcoded_sizes(doc):
    _assert_clean(check_hardcoded_sizes(doc, doc.read_text()))


def test_readme_has_no_stale_setup_path():
    readme = ROOT / "README.md"
    _assert_clean(check_readme_setup_path(readme, readme.read_text()))
