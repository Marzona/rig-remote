FAKE = Path("FAKE.md")


def _make_src(tmp_path: Path) -> Path:
    pkg = tmp_path / "rig_remote"
    (pkg / "sub").mkdir(parents=True)
    for file in (pkg / "__init__.py", pkg / "alpha.py", pkg / "sub" / "__init__.py"):
        file.write_text("")
    return tmp_path


@pytest.mark.parametrize(
    "text",
    [
        "See `src/rig_remote/does_not_exist.py` for details.",
        "See `nonexistent_module.py`.",
        "Run via `scripts/missing_script.sh`.",
        "See `tests/test_nothing_here.py::test_x`.",
        "Config in `etc/rig-remote/other.ini`.",
    ],
)
def test_check_path_references_flags_missing(text):
    assert check_path_references(FAKE, text)


@pytest.mark.parametrize(
    "text",
    [
        "Existing `pyproject.toml` and `src/rig_remote/scanner_core.py`.",
        "Bare module `scanner_core.py` and package `rig_backends/`.",
        "Node id `tests/test_architecture.py::test_no_async_code`.",
        "Commands and globs are ignored: `uv sync --group dev`, `tests/*.py`, `<stage>`, `v*`, `a=b/c`.",
        "```bash\ncat src/rig_remote/not_real.py\n```",
        "URL `https://example.org/a/b.md` is ignored.",
        "Allowlisted `dist/` and `~/.config/x` and `release_message.md`.",
    ],
)
def test_check_path_references_accepts_valid_or_non_paths(text):
    assert check_path_references(FAKE, text) == []


@pytest.mark.parametrize("ref", ["/usr", "/tmp", "/usr/lib/rig-remote/", "/etc/passwd"])
def test_check_path_references_flags_unlisted_absolute_path_even_if_host_has_it(ref):
    problems = check_path_references(FAKE, f"See `{ref}`.")
    assert len(problems) == 1
    assert "FAKE.md" in problems[0]
    assert ref in problems[0]
    assert "ALLOWED_REFS" in problems[0]
    assert "repo-relative" in problems[0]


def test_check_path_references_accepts_allowlisted_absolute_path():
    assert check_path_references(FAKE, "Installed in `/usr/lib/rig-remote`.") == []


def test_check_path_references_ignores_lone_slash_separator():
    assert check_path_references(FAKE, "Use `/` as separator.") == []


def test_check_path_references_resolves_relative_path_inside_repo(tmp_path):
    (tmp_path / "docs").mkdir()
    (tmp_path / "docs" / "a.md").write_text("")
    assert check_path_references(FAKE, "See `docs/a.md`.", tmp_path) == []
    assert check_path_references(FAKE, "See `docs/b.md`.", tmp_path)


def test_check_path_references_rejects_relative_path_escaping_repo(tmp_path):
    root = tmp_path / "repo"
    root.mkdir()
    (tmp_path / "outside.md").write_text("")
    assert check_path_references(FAKE, "See `../outside.md`.", root)


def test_check_path_references_rejects_symlink_leaving_repo(tmp_path):
    root = tmp_path / "repo"
    root.mkdir()
    (tmp_path / "outside.md").write_text("")
    (root / "link.md").symlink_to(tmp_path / "outside.md")
    assert check_path_references(FAKE, "See `link.md` and `sub/link.md`.", root)


@pytest.mark.parametrize("ref", ["/usr", "/tmp", "/usr/lib/rig-remote", "~/.config/x", "~/x/y.md"])
def test_check_path_references_never_stats_host_paths(ref, monkeypatch, tmp_path):
    seen: list[Path] = []
    real_exists = Path.exists

    def recording_exists(self, *args, **kwargs):
        seen.append(self)
        return real_exists(self, *args, **kwargs)

    monkeypatch.setattr(Path, "exists", recording_exists)
    check_path_references(FAKE, f"See `{ref}`.", tmp_path)
    assert all(p.is_relative_to(tmp_path) for p in seen), seen


def test_check_modules_documented_flags_missing_module(tmp_path):
    src = _make_src(tmp_path)
    problems = check_modules_documented(FAKE, "Only `alpha.py` is described.", src)
    assert len(problems) == 1
    assert "`sub`" in problems[0]


def test_check_modules_documented_accepts_all_named(tmp_path):
    src = _make_src(tmp_path)
    assert check_modules_documented(FAKE, "`alpha.py` and `sub/` are described.", src) == []


