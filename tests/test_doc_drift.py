"""Documentation drift checks for ``.claude/**/*.md`` and ``README.md``.

Each check is a function over ``(path, text)`` (plus optional repository
context) returning a list of human-readable problems, so every check can be
exercised against known-bad snippets and then run against the real docs.

A3.1 heuristic (what counts as a repository path)
-------------------------------------------------
Only inline backtick spans outside fenced code blocks are inspected.  A span
is a path reference when it has no whitespace and none of ``* ? < > { } [ ] ( )
$ = , ; | " '`` (which marks commands, globs, placeholders and code
snippets), is not a URL, and either contains ``/`` or ends in a known
extension (``.py .md .sh .toml .yml .yaml .json .ini .csv .cfg .lock``).
A ``::`` suffix (pytest node id) is dropped first.  A reference resolves when
it exists relative to the repo root, ``src/`` or ``src/rig_remote/``; a bare
file name also resolves when it exists anywhere under ``src/``, ``tests/``,
``functional_tests/``, ``.claude/`` or ``.github/``.  Anything else must have
an explicit entry in ``ALLOWED_REFS`` / ``ALLOWED_PREFIXES`` with a reason.

Hermeticity: every filesystem lookup is confined to the repository tree.
Absolute references (``/usr/lib/...``) are never looked up on the host; they
pass only when listed in ``ALLOWED_REFS``.  ``~`` is never expanded, ``..``
segments and symlinks that leave the repo do not count as existing, and a
span made only of ``/`` characters is a separator, not a path.
"""

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"

DOC_PATHS = [ROOT / "README.md", *sorted((ROOT / ".claude").rglob("*.md"))]

PATH_EXTENSIONS = (".py", ".md", ".sh", ".toml", ".yml", ".yaml", ".json", ".ini", ".csv", ".cfg", ".lock")
NON_PATH_CHARS = set("*?<>{}[]()$=,;|\"'")
SEARCH_DIRS = ("src", "tests", "functional_tests", ".claude", ".github")
SKIP_DIR_NAMES = {"__pycache__", ".mypy_cache", ".ruff_cache", "rig_remote.egg-info", ".venv"}

# Exact references that legitimately do not exist in a clean checkout.
ALLOWED_REFS: dict[str, str] = {
    "release_message.md": "generated by './release.sh release'; not tracked",
    "rig-bookmarks.csv": "default name of the user's bookmark file; created at runtime, not in the repo",
    "Marzona/rig-remote": "GitHub owner/repo slug, not a file path",
    "debian/changelog": "optional Debian packaging file ('if present'); the debian tree is not tracked",
    "dist": "build output directory; generated by './release.sh package'",
    "/usr/lib/rig-remote": "install location of the .deb's private site-packages; exists only on installed systems",
}
# Prefixes (references starting with them) that are allowed to be absent.
ALLOWED_PREFIXES: dict[str, str] = {
    "dist/": "build output directory; generated by './release.sh package'",
    "~/": "per-user home path; exists only on a user's machine",
    ".venv/": "local virtualenv; not tracked",
}

# Modules/subpackages under src/ that need not be named in design.md/architecture.md.
ALLOWED_UNDOCUMENTED_MODULES: dict[str, str] = {}

FENCE_RE = re.compile(r"```.*?```", re.DOTALL)
SPAN_RE = re.compile(r"(?<!`)`([^`\n]+)`(?!`)")
ADR_REF_RE = re.compile(r"\bADR-(\d+)\b")
ADR_HEADING_RE = re.compile(r"^#{2,4}\s+ADR-(\d+)\b", re.MULTILINE)
RELEASE_STAGE_RE = re.compile(r"\./release\.sh\s+([A-Za-z_][\w-]*)")
HARDCODED_SIZE_RE = re.compile(r"\b(\d[\d,]*)\s*(?:LOC|lines?)\b", re.IGNORECASE)
ALLOWED_SIZES = {"600"}


def _spans(text: str) -> list[str]:
    return SPAN_RE.findall(FENCE_RE.sub("", text))


def _is_path_reference(span: str) -> bool:
    if not span or any(c.isspace() for c in span) or "://" in span:
        return False
    if any(c in NON_PATH_CHARS for c in span) or span.startswith("-") or "@" in span:
        return False
    if not span.strip("/"):
        return False  # "/" alone is a separator in prose, not a path
    return "/" in span or span.endswith(PATH_EXTENSIONS)


def _in_repo_exists(candidate: Path, root: Path) -> bool:
    """True when ``candidate`` exists and, after resolving symlinks and '..', is inside ``root``."""
    resolved_root = root.resolve()
    return candidate.exists() and candidate.resolve().is_relative_to(resolved_root)


def _exists(ref: str, root: Path) -> bool:
    """Whether a reference exists inside the repository; never consults the host outside ``root``."""
    if ref.startswith("/"):
        return False  # absolute host paths are never looked up; they need an allowlist entry
    ref = ref.removeprefix("./").rstrip("/")
    if not ref:
        return True
    if "/" in ref:
        return any(_in_repo_exists(base / ref, root) for base in (root, root / "src", root / "src" / "rig_remote"))
    if _in_repo_exists(root / ref, root):
        return True
    for name in SEARCH_DIRS:
        base = root / name
        if base.is_dir() and any(
            not SKIP_DIR_NAMES.intersection(p.relative_to(base).parts) and _in_repo_exists(p, root)
            for p in base.rglob(ref)
        ):
            return True
    return False


def _is_allowed_ref(ref: str) -> bool:
    return ref in ALLOWED_REFS or any(ref.startswith(p) for p in ALLOWED_PREFIXES)


def check_path_references(path: Path, text: str, root: Path = ROOT) -> list[str]:
    """A3.1: every backticked repository path or module name exists."""
    problems = []
    for span in dict.fromkeys(_spans(text)):
        ref = span.split("::")[0]
        if not _is_path_reference(ref) or _is_allowed_ref(ref):
            continue
        if not _exists(ref, root):
            if ref.startswith("/"):
                problems.append(
                    f"{path.name}: `{span}` is an absolute path and is never checked against the host. "
                    "Fix: add it to ALLOWED_REFS in tests/test_doc_drift.py with a reason, "
                    "or use a repo-relative path."
                )
                continue
            problems.append(
                f"{path.name}: `{span}` does not exist. Fix: correct the path, remove the "
                "reference, or add it to ALLOWED_REFS in tests/test_doc_drift.py with a reason."
            )
    return problems


def _src_modules(src_root: Path) -> list[str]:
    """Top-level modules and subpackages of every package directly under src/."""
    names: list[str] = []
    for package in sorted(p for p in src_root.iterdir() if p.is_dir() and (p / "__init__.py").exists()):
        if package.name in SKIP_DIR_NAMES or package.name.endswith(".egg-info"):
            continue
        if package.name != "rig_remote":
            names.append(package.name)
        for child in sorted(package.iterdir()):
            if child.name in SKIP_DIR_NAMES or child.name == "__init__.py":
                continue
            if child.is_dir() and (child / "__init__.py").exists():
                names.append(child.name)
            elif child.suffix == ".py":
                names.append(child.stem)
    return names


def check_modules_documented(path: Path, text: str, src_root: Path = SRC) -> list[str]:
    """A3.2: every module/subpackage under src/ is named in the design docs (``text``)."""
    problems = []
    for name in _src_modules(src_root):
        if name in ALLOWED_UNDOCUMENTED_MODULES:
            continue
        if not re.search(rf"(?<![\w]){re.escape(name)}(?![\w])", text):
            problems.append(
                f"{path.name}: module/subpackage `{name}` under src/ is not mentioned. Fix: describe it in "
                ".claude/design.md (or architecture.md), or add it to ALLOWED_UNDOCUMENTED_MODULES with a reason."
            )
    return problems


def _test_names(root: Path) -> set[str]:
    names: set[str] = set()
    for folder in ("tests", "functional_tests"):
        for file in (root / folder).rglob("*.py"):
            names.update(re.findall(r"^\s*(?:async\s+)?def\s+(test_\w+)", file.read_text(), re.MULTILINE))
    return names


def check_invariant_tests(path: Path, text: str, root: Path = ROOT) -> list[str]:
    """A3.3: test files and functions named in table rows exist."""
    problems = []
    known: set[str] | None = None
    for line in text.splitlines():
        if not line.lstrip().startswith("|"):
            continue
        for span in _spans(line):
            ref, _, func = span.partition("::")
            is_file = ref.endswith(".py") and ref.split("/")[-1].startswith("test_")
            if is_file and not _is_allowed_ref(ref) and not _exists(ref, root):
                problems.append(
                    f"{path.name}: test file `{ref}` named in the table does not exist. "
                    "Fix: update the 'Enforced by' cell to the real test file."
                )
            name = func or (ref if re.fullmatch(r"test_\w+", ref) else "")
            if name:
                known = _test_names(root) if known is None else known
                if name not in known:
                    problems.append(
                        f"{path.name}: test function `{name}` named in the table does not exist under tests/. "
                        "Fix: rename the reference to an existing test or add the test."
                    )
    return problems


def check_adr_references(path: Path, text: str, known: set[str]) -> list[str]:
    """A3.4: every ADR-N cited exists as a heading in architecture.md."""
    return [
        f"{path.name}: cites ADR-{n}, which has no heading in .claude/architecture.md. "
        "Fix: correct the number or add the ADR."
        for n in dict.fromkeys(ADR_REF_RE.findall(text))
        if n not in known
    ]


def release_stages(release_sh_text: str) -> set[str]:
    """Labels handled by the ``case "${stage}" in`` statement of release.sh."""
    match = re.search(r'case\s+"\$\{stage\}"\s+in(.*?)\n\s*esac', release_sh_text, re.DOTALL)
    body = match.group(1) if match else ""
    stages: set[str] = set()
    for label in re.findall(r"^\s*([A-Za-z_][\w|-]*)\)", body, re.MULTILINE):
        stages.update(label.split("|"))
    return stages


def check_release_stages(path: Path, text: str, stages: set[str]) -> list[str]:
    """A3.5: every ``./release.sh <stage>`` named in the docs is handled by release.sh."""
    return [
        f"{path.name}: `./release.sh {s}` is not a stage handled by release.sh (valid: {', '.join(sorted(stages))}). "
        "Fix: use a valid stage or update the doc."
        for s in dict.fromkeys(RELEASE_STAGE_RE.findall(text))
        if s not in stages
    ]


def check_hardcoded_sizes(path: Path, text: str) -> list[str]:
    """A3.6: no hardcoded module sizes (the 600-line limit is allowed)."""
    return [
        f"{path.name}: hardcoded size '{m.group(0)}' goes stale. "
        "Fix: remove the number (the 600-line limit is the only allowed one)."
        for m in HARDCODED_SIZE_RE.finditer(text)
        if m.group(1) not in ALLOWED_SIZES
    ]


def check_readme_setup_path(path: Path, text: str) -> list[str]:
    """A3.7: the README must not tell users to ``cd rig-remote/rig-remote``."""
    if "cd rig-remote/rig-remote" in text:
        return [
            f"{path.name}: contains 'cd rig-remote/rig-remote'. "
            "Fix: the repo root contains pyproject.toml; use 'cd rig-remote' after cloning."
        ]
    return []


